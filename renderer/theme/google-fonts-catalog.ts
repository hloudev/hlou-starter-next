const BY_FAMILY = new Map(GOOGLE_FONTS_CATALOG.map((entry) => [entry.family.toLowerCase(), entry]));

/** The generic CSS fallback a family's category maps to; `sans-serif` for an unlisted family. */
export function fontCategory(family: string): GoogleFontCategory {
  return BY_FAMILY.get(family.toLowerCase())?.category ?? 'sans-serif';
}

export function searchGoogleFonts(query: string, limit = 20): GoogleFontCatalogEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return GOOGLE_FONTS_CATALOG.slice(0, limit);
  return GOOGLE_FONTS_CATALOG.filter((entry) => entry.family.toLowerCase().includes(q)).slice(
    0,
    limit
  );
}
